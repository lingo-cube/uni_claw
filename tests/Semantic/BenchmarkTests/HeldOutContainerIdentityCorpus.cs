/// <summary>
/// HELD-OUT Container Identity corpus — ContainerIdentity-heldout-v1.
///
/// Purpose: independent validation corpus for the frozen
/// BGE_SMALL_CONTAINER_IDENTITY_PROFILE_V1. It MUST NOT be used for tuning.
///
/// Isolation contract (proven by HeldOutValidationTests.T1):
/// - No case id appears in any tuning corpus
///   (DeveloperOptionsBenchmarkCorpus, ContainerIdentityCorpora,
///    ExpandedContainerIdentityCorpora golden+regression+adversarial).
/// - No case shares the same multiset of (text, perception type, switch state)
///   element tuples with any tuning corpus case.
///
/// Coverage: 4 identities x 12 cases = 48 cases, per identity:
///   A x2 Normal (title visible)
///   B x2 Title-offscreen / scroll
///   C x2 Partial observation
///   D x1 Low-information observation (expect abstain)
///   E x2 Similar-page interference (expect abstain)
///   F x3 Hard negative:
///        F1 wrong container (regression family, source Regression)
///        F2 visually/text-overlap similar container (adversarial family)
///        F3 insufficient / empty or near-empty semantic query
///
/// Sources: RealTrace (verbatim or contiguous-subset observations captured in
/// committed traces: openspec/.../uitars-bench/truth.json
/// root-top / root-scrolled / accessibility / display-child, and the Wi-Fi /
/// DeveloperOptions traces documented in docs/experiments/qwen2.5-vl-local-preview.md),
/// Manual (authored from real Settings-app knowledge, possibly derived from a
/// real trace with edits), Synthetic (adversarial constructions), Regression
/// (new variants of documented historical failure families — never verbatim
/// tuning cases).
/// </summary>
