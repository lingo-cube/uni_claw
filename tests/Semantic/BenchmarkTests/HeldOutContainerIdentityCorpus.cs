            PreviousVerifiedIdentity = previousVerifiedIdentity,
            ViewportState = viewport,
            VisibleAnchorState = anchor,
            NoiseLevel = noise,
            AmbiguityLevel = ambiguity,
            ScrollPosition = scroll,
        };

