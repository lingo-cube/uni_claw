using UniClaw.Kernel.Run;
using UniClaw.Kernel.World;
using UniClaw.Kernel.Evidence;
var allowed = new HashSet<string> { "tap" };
var scope = new HashSet<string> { "ui.test" };
var proof = new List<string> { "done" };
var contract = new ExecutionContract("v1", "test", scope, allowed, new HashSet<string>(), proof, TaskInstanceId:"task",ProductSessionId:"session",ContractRef:"contract",AcceptedContractViewRef:"view",ContractGeneration:1);
var run = new RunModel();
var admitted = run.AdmitContract(contract);
Console.WriteLine($"contract_admitted={admitted.Accepted}");
var id = run.RunId;
Console.WriteLine($"before_new_effect={run.View!.AllowedEffects.Contains("new-effect")}");
allowed.Add("new-effect");
Console.WriteLine($"after_new_effect={run.View!.AllowedEffects.Contains("new-effect")};run_id_unchanged={id==run.RunId}");
Console.WriteLine($"world_history_runtime_type={new WorldModel(scope).RevisionHistory.GetType().Name};is_mutable_list={new WorldModel(scope).RevisionHistory is List<WorldBeliefRevision>}");
var lineage = new List<string> { "raw" };
var ledger = new EvidenceLedger();
var observation = new ObservationProposal(new ObservationClaim("ui.test", "on"), IngressKind.Observation, ObservationContext.External, new Provenance("test", DateTimeOffset.UtcNow, "ui.test", lineage));
var (admission, record) = ledger.Admit(observation);
Console.WriteLine($"evidence_admitted={admission.Decision};lineage_before={record!.Provenance.TransformationLineage.Count}");
var evidenceId = record.EvidenceId;
lineage.Add("never-admitted");
Console.WriteLine($"lineage_after={record.Provenance.TransformationLineage.Count};evidence_id_unchanged={evidenceId==record.EvidenceId}");
var world = new WorldModel(scope);
world.Reconcile(record,world.JudgeRelevance(record));
Console.WriteLine($"world_current_before_clear={world.Current is not null}");
((List<WorldBeliefRevision>)world.RevisionHistory).Clear();
Console.WriteLine($"world_current_after_clear={world.Current is not null}");
